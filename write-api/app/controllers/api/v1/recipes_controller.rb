module Api
  module V1
    # Writes only. Reads go to the Go read-api: GET /api/v1/recipes(/:id),
    # and GET /api/v1/public/recipes/:public_id (no login) once is_public is true.
    # Lookups are scoped to the caller (and RLS backs that up), so another
    # user's recipe is a 404, never a 403.
    class RecipesController < ApplicationController
      def create
        authorize Recipe
        recipe = Recipe.new(recipe_params.merge(owner_sub: current_user_sub))
        return render_errors(recipe) unless recipe.save_with_unique_public_id

        render json: { id: recipe.id, recipe: recipe }, status: :created
      end

      def update
        recipe = Recipe.owned_by(current_user_sub).find(params[:id])
        authorize recipe
        return render_errors(recipe) unless recipe.update(recipe_params)

        render json: { id: recipe.id, recipe: recipe }
      end

      def destroy
        recipe = Recipe.owned_by(current_user_sub).find(params[:id])
        authorize recipe
        recipe.destroy!

        render json: { id: recipe.id }
      end

      private
        # image_key is deliberately not permitted (only RecipeImagesController
        # sets it, to a file it just stored), and public_id is generated by the model.
        def recipe_params
          params.expect(recipe: [ :title, :is_public, ingredients: [], directions: [] ])
        end
    end
  end
end
